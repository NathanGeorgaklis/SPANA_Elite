# REBUILT 2026-10 — NOT ORIGINAL SOURCE
# Evidence basis: R2/R2_PREREGISTRATION.md §4 (labels drawn from the clip's own frames, no model output shown)
"""Build the offline R2 annotation pack from the verified lossless clips:

    PACK/index.html                 (copy of tools_rb/r2_annotator.html)
    PACK/r2_clips_manifest.js       (clip list: id, split, fps, frames, size, sha256, proposed target pointer)
    PACK/frames/<clip_id>/f_NNNNNN.jpg   (every frame, JPEG q2, frame index = clip frame index, exact by construction)
    PACK/PACK_RECORD.json           (sha256 of index.html and the manifest; per-clip frame counts)

    python3 tools_rb/r2_annotation_pack.py SELECTION_JSON CLIPS_DIR PACK_DIR [CLIP_ID ...]

No tracker, detector or model is run. Refuses to overwrite an existing clip's frame folder.
"""
import glob
import hashlib
import json
import os
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
JPEG_Q = 2


def _sha(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for b in iter(lambda: f.read(1 << 20), b""):
            h.update(b)
    return h.hexdigest()


def main(selection_json, clips_dir, pack_dir, ids):
    with open(selection_json) as f:
        sel = json.load(f)
    os.makedirs(os.path.join(pack_dir, "frames"), exist_ok=True)
    manifest = []
    record = {"tool": "tools_rb/r2_annotation_pack.py", "jpeg_q": JPEG_Q, "clips": {}}
    for c in sel["clips"]:
        with open(os.path.join(clips_dir, c["clip_id"] + ".extract.json")) as f:
            ext = json.load(f)
        mp4 = os.path.join(clips_dir, c["clip_id"] + ".mp4")
        out = os.path.join(pack_dir, "frames", c["clip_id"])
        if (not ids or c["clip_id"] in ids) and not os.path.isdir(out):
            if _sha(mp4) != ext["clip_sha256"]:
                raise SystemExit(f"{mp4} hash differs from its extract record (fail closed)")
            tmp = out + ".partial"
            os.makedirs(tmp)
            subprocess.run(["ffmpeg", "-v", "error", "-i", mp4, "-q:v", str(JPEG_Q), "-start_number", "0",
                            os.path.join(tmp, "f_%06d.jpg")], check=True)
            os.rename(tmp, out)
        n = len(glob.glob(os.path.join(out, "f_*.jpg"))) if os.path.isdir(out) else 0
        if os.path.isdir(out) and n != ext["frames"]:
            raise SystemExit(f"{c['clip_id']}: {n} frames extracted, expected {ext['frames']}")
        probe = subprocess.run(["ffprobe", "-v", "error", "-select_streams", "v:0", "-show_entries",
                                "stream=width,height", "-of", "json", mp4], check=True, capture_output=True, text=True)
        st = json.loads(probe.stdout)["streams"][0]
        manifest.append({"clip_id": c["clip_id"], "split": ext["split"], "source": c["source"], "fps": ext["fps"],
                         "frames": ext["frames"], "width": st["width"], "height": st["height"],
                         "clip_sha256": ext["clip_sha256"], "proposed_target": c["proposed_target"],
                         "proposed_seed_s": c["proposed_seed_s"], "frames_ready": n == ext["frames"]})
        record["clips"][c["clip_id"]] = {"frames": n, "ready": n == ext["frames"]}
    shutil.copyfile(os.path.join(HERE, "r2_annotator.html"), os.path.join(pack_dir, "index.html"))
    with open(os.path.join(pack_dir, "r2_clips_manifest.js"), "w") as f:
        f.write("// generated by tools_rb/r2_annotation_pack.py; do not edit\nwindow.R2_CLIPS = ")
        json.dump([m for m in manifest if m["frames_ready"]], f, indent=1)
        f.write(";\n")
    record["index_html_sha256"] = _sha(os.path.join(pack_dir, "index.html"))
    record["manifest_sha256"] = _sha(os.path.join(pack_dir, "r2_clips_manifest.js"))
    with open(os.path.join(pack_dir, "PACK_RECORD.json"), "w") as f:
        json.dump(record, f, indent=1, sort_keys=True)
        f.write("\n")
    print(json.dumps({k: v for k, v in record.items() if k != "clips"}),
          sum(v["ready"] for v in record["clips"].values()), "clips ready")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2], sys.argv[3], sys.argv[4:])
